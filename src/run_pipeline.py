"""Run the complete training, tuning, and frozen evaluation pipeline.

Run from any working directory with:
    python3 src/run_pipeline.py --bootstrap 1000

This creates a new evaluation directory and never overwrites a frozen
Stage-5 evaluation. Training outputs in results/ are regenerated by design.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def run_step(label: str, command: list[str]) -> None:
    print(f"\n{'=' * 78}\n{label}\n{'=' * 78}", flush=True)
    subprocess.run(command, cwd=ROOT, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bootstrap", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=ROOT / "results/evaluation_runs/reproduction",
        help="New output directory for frozen predictions and evaluation.",
    )
    args = parser.parse_args()
    if args.bootstrap < 100:
        parser.error("--bootstrap must be at least 100 (1000 recommended)")

    output_dir = args.output_dir.resolve()
    if (output_dir / "manifest.json").exists():
        parser.error(
            f"{output_dir} already contains a frozen evaluation. Choose a new --output-dir."
        )

    py = sys.executable
    run_step("1/7 — Baseline models", [py, "src/baselines.py"])
    run_step("2/7 — Original MLP", [py, "src/mlp.py"])
    run_step("3/7 — Main hyperparameter sweep", [py, "src/tuning.py", "--stage", "main", "--rerun"])
    run_step("4/7 — Seed and class-weight experiments", [py, "src/tuning.py", "--stage", "extra", "--rerun"])
    run_step("5/7 — Validation threshold analysis", [py, "src/threshold_analysis.py"])
    run_step(
        "6/7 — Freeze validation protocol and predict test",
        [py, "src/predict_test.py", "--output-dir", str(output_dir)],
    )
    run_step(
        "7/7 — Generate evaluation tables and report",
        [
            py,
            "src/evaluation.py",
            "--output-dir",
            str(output_dir),
            "--bootstrap",
            str(args.bootstrap),
            "--seed",
            str(args.seed),
        ],
    )
    run_step("Unit tests", [py, "-m", "unittest", "discover", "-s", "tests", "-v"])
    print(f"\nPipeline completed. Evaluation artifacts: {output_dir}", flush=True)


if __name__ == "__main__":
    main()
